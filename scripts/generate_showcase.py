#!/usr/bin/env python3
"""Regenerate SHOWCASE.md from the example projects.

For each project in examples/showcase, the document shows the source and the schedule
`plan report` produces from it. It is generated, never hand-edited: a document
that has been edited since it was generated says nothing about the tool, and
the previous one had been.

    python scripts/generate_showcase.py            # write SHOWCASE.md
    python scripts/generate_showcase.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "examples" / "showcase"
OUTPUT = ROOT / "SHOWCASE.md"
TIMEOUT = 600


def render(path: Path) -> tuple[bool, str]:
    """Run `plan report` on one project; return (succeeded, output)."""
    done = subprocess.run(
        [sys.executable, "-m", "scriptplan.cli.plan", "report", "--csv", str(path)],
        capture_output=True,
        text=True,
        cwd=str(ROOT),
        env={"PATH": "/usr/bin:/bin", "PYTHONPATH": str(ROOT), "HOME": str(Path.home())},
        timeout=TIMEOUT,
    )
    if done.returncode != 0:
        return False, (done.stderr or "").strip()
    return True, done.stdout.strip()


def build() -> str:
    projects = sorted(FIXTURES.glob("*.tjp"))
    sys.path.insert(0, str(ROOT))
    from scriptplan import __version__

    lines: list[str] = [
        "# ScriptPlan example projects",
        "",
        f"**ScriptPlan**: {__version__}  ",
        f"**Generated**: {datetime.now(timezone.utc):%Y-%m-%d %H:%M:%S} UTC  ",
        "**Command**: `plan report --csv <project>`",
        "",
        "Every project in `examples/showcase`, with the schedule ScriptPlan produces for it.",
        "",
        "This file is generated by `scripts/generate_showcase.py`. Do not edit it:",
        "regenerate it, so that what it shows is what the tool does.",
        "",
        "Each schedule here is also pinned as a golden snapshot in",
        "`tests/golden/fixtures`, so a change that moves a date fails the test suite",
        "rather than quietly changing this document.",
        "",
        "---",
        "",
        "## Contents",
        "",
    ]
    for index, path in enumerate(projects, start=1):
        anchor = path.name.replace(".", "").replace("_", "-")
        lines.append(f"{index}. [{path.name}](#{index}-{anchor})")
    lines += ["", "---", ""]

    failures = 0
    for index, path in enumerate(projects, start=1):
        anchor = path.name.replace(".", "").replace("_", "-")
        ok, output = render(path)
        if not ok:
            failures += 1
        lines += [
            f'<h2 id="{index}-{anchor}">{index}. {path.name}</h2>',
            "",
            "**Project**",
            "",
            "```",
            path.read_text().rstrip(),
            "```",
            "",
            "**Schedule**" if ok else "**Not scheduled**",
            "",
            "```",
            output or "(no output)",
            "```",
            "",
            "---",
            "",
        ]

    lines += [
        "## Summary",
        "",
        f"| Projects | {len(projects)} |",
        "|---|---|",
        f"| Scheduled | {len(projects) - failures} |",
        f"| Not scheduled | {failures} |",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if SHOWCASE.md is out of date")
    args = parser.parse_args()

    generated = build()
    if not args.check:
        OUTPUT.write_text(generated)
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(generated.splitlines())} lines)")
        return 0

    if not OUTPUT.exists():
        print("SHOWCASE.md is missing; run scripts/generate_showcase.py")
        return 1
    # The timestamp line always differs, so compare everything else.
    def body(text: str) -> list[str]:
        return [line for line in text.splitlines() if not line.startswith("**Generated**")]

    if body(OUTPUT.read_text()) != body(generated):
        print("SHOWCASE.md is out of date; run scripts/generate_showcase.py")
        return 1
    print("SHOWCASE.md is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
